/**
 * Sistema's own token pipeline (tokens.pipeline). Sources: tokens/src/*.json (DTCG).
 * Files named <category>.<mode>.json are modes. palette.json is the primitive tier:
 * roles refer to it, but it isn't output, so code can only use roles.
 *
 * Writes:
 *   src/styles/tokens/generated.css    custom properties, light and dark
 *   src/styles/tokens/tailwind-theme.json  the role names for tailwind.config.ts
 *   DESIGN.md front matter               regenerated from the sources
 *   sistema-review/token-check.html      the review page for foundations-approved
 */
import fs from 'node:fs'
import StyleDictionary from 'style-dictionary'

const SRC = 'tokens/src'
const files = fs.readdirSync(SRC).filter(f => f.endsWith('.json'))
const defaults = files.filter(f => f.split('.').length === 2)
const modes = files.filter(f => f.split('.').length === 3)

/** Resolve every token with Style Dictionary, returning { path: value } for the files given. */
async function resolve(sources, keepFrom) {
  const out = {}
  StyleDictionary.registerFormat({
    name: 'sistema/collect',
    format: ({ dictionary }) => {
      for (const t of dictionary.allTokens) {
        if (keepFrom && !keepFrom.some(f => t.filePath.endsWith(f))) continue
        out[t.path.join('.')] = { value: t.$value ?? t.value, type: t.$type ?? t.type, description: t.$description ?? t.description }
      }
      return ''
    },
  })
  const sd = new StyleDictionary({
    source: sources.map(f => `${SRC}/${f}`),
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: { collect: { transforms: ['attribute/cti'], files: [{ destination: '.collect', format: 'sistema/collect' }], buildPath: '.sd-tmp/' } },
  })
  await sd.buildAllPlatforms()
  fs.rmSync('.sd-tmp', { recursive: true, force: true })
  return out
}

const base = await resolve(defaults)
const dark = await resolve([...defaults, ...modes.filter(f => f.includes('.dark.'))], modes.filter(f => f.includes('.dark.')))

// Modes may only replace tokens the defaults have.
for (const k of Object.keys(dark)) if (!(k in base)) throw new Error(`Mode token ${k} has no default.`)

const shadowCss = v => (Array.isArray(v) ? v : [v]).map(s => `${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} ${s.color}`).join(', ')
const cssVars = (tokens, filter = () => true) => {
  const lines = []
  for (const [path, t] of Object.entries(tokens)) {
    const [cat, ...rest] = path.split('.')
    if (cat === 'palette' || !filter(path)) continue
    const name = `--${cat}-${rest.join('-')}`
    if (t.type === 'typography') {
      const v = t.value
      lines.push(`  ${name}-family: ${Array.isArray(v.fontFamily) ? v.fontFamily.join(', ') : v.fontFamily};`, `  ${name}-size: ${v.fontSize};`, `  ${name}-weight: ${v.fontWeight};`, `  ${name}-line-height: ${v.lineHeight};`, `  ${name}-tracking: ${v.letterSpacing};`)
    } else if (t.type === 'shadow') lines.push(`  ${name}: ${shadowCss(t.value)};`)
    else if (t.type === 'fontFamily') lines.push(`  ${name}: ${Array.isArray(t.value) ? t.value.map(f => (f.includes(' ') ? `"${f}"` : f)).join(', ') : t.value};`)
    else if (typeof t.value === 'string' || typeof t.value === 'number') lines.push(`  ${name}: ${t.value};`)
  }
  return lines
}

const darkVars = cssVars(dark).filter(l => !l.includes('--font-') && !l.includes('--type-'))
const css = [
  '/* Generated by style-dictionary.config.mjs from tokens/src. Do not edit; run `npm run tokens`. */',
  ':root {', ...cssVars(base), '}',
  '[data-theme="dark"] {', ...darkVars, '}',
  '@media (prefers-color-scheme: dark) {', '  :root:not([data-theme="light"]) {', ...darkVars.map(l => '  ' + l), '  }', '}',
  '',
].join('\n')
fs.writeFileSync('src/styles/tokens/generated.css', css)

// Self-reference check.
for (const m of css.matchAll(/--([a-z0-9-]+):\s*var\(--([a-z0-9-]+)\)/g)) if (m[1] === m[2]) throw new Error(`--${m[1]} refers to itself`)

// Tailwind theme: role names only.
const roles = Object.keys(base).filter(k => k.startsWith('color.')).map(k => k.slice(6))
const theme = {
  colors: Object.fromEntries(roles.map(r => [r, `var(--color-${r})`])),
  fontSize: Object.fromEntries(Object.keys(base).filter(k => k.startsWith('type.')).map(k => {
    const r = k.slice(5)
    return [r, [`var(--type-${r}-size)`, { lineHeight: `var(--type-${r}-line-height)`, letterSpacing: `var(--type-${r}-tracking)`, fontWeight: `var(--type-${r}-weight)` }]]
  })),
  borderRadius: Object.fromEntries(Object.keys(base).filter(k => k.startsWith('radius.')).map(k => [`radius-${k.slice(7)}`, `var(--radius-${k.slice(7)})`])),
  boxShadow: Object.fromEntries(Object.keys(base).filter(k => k.startsWith('shadow.')).map(k => [k.slice(7), `var(--shadow-${k.slice(7)})`])),
  spacing: Object.fromEntries(Object.keys(base).filter(k => k.startsWith('layout.')).map(k => [k.slice(7), `var(--layout-${k.slice(7)})`])),
}
fs.writeFileSync('src/styles/tokens/tailwind-theme.json', JSON.stringify(theme, null, 2) + '\n')

// DESIGN.md front matter.
const sistema = JSON.parse(fs.readFileSync('sistema.json', 'utf8'))
const y = v => JSON.stringify(v)
const fm = ['# Generated from tokens/src by `npm run tokens`. Do not edit.', `name: ${y(sistema.project?.name ?? 'Sistema')}`, 'colors:']
for (const r of roles) fm.push(`  ${r}: ${y(base['color.' + r].value)}`)
fm.push('typography:')
for (const k of Object.keys(base).filter(k => k.startsWith('type.'))) {
  const v = base[k].value
  fm.push(`  ${k.slice(5)}: { fontFamily: ${y(Array.isArray(v.fontFamily) ? v.fontFamily[0] : String(v.fontFamily).split(',')[0])}, fontSize: ${parseInt(v.fontSize)}, fontWeight: ${v.fontWeight}, lineHeight: ${v.lineHeight} }`)
}
fm.push('rounded:')
for (const k of Object.keys(base).filter(k => k.startsWith('radius.'))) fm.push(`  ${k.slice(7)}: ${parseInt(base[k].value)}`)
fm.push('spacing:')
for (const k of Object.keys(base).filter(k => k.startsWith('space.'))) fm.push(`  ${k.slice(6)}: ${parseInt(base[k].value)}`)
const design = fs.readFileSync('DESIGN.md', 'utf8')
const body = design.startsWith('---') ? design.slice(design.indexOf('\n---', 3) + 4) : design
fs.writeFileSync('DESIGN.md', `---\n${fm.join('\n')}\n---${body}`)

// Token check page.
const { buildTokenCheck } = await import('./tools/token-check.mjs')
fs.writeFileSync('sistema-review/token-check.html', buildTokenCheck({ base, dark, sistema }))
console.log(`tokens: ${Object.keys(base).length} defaults, ${Object.keys(dark).length} dark`)
