// Compiles the DTCG token sources in tokens/src/ (the only place token values are written).
// Generated outputs, never edit by hand:
//   src/styles/tokens/tokens.css          CSS custom properties: defaults on :root, modes under their selectors
//   src/styles/tokens/tailwind-theme.css  Tailwind 4 @theme mapping of role tokens
//   DESIGN.md front matter                 token values for agents that read DESIGN.md
// Run with: npm run tokens
import StyleDictionary from 'style-dictionary';
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import path from 'node:path';

const SRC = 'tokens/src';
const OUT = 'src/styles/tokens';
const HEADER = '/* Generated by style-dictionary.config.mjs from tokens/src/. Do not edit by hand. */';

// ---- Sources and modes ---------------------------------------------------
// <category>.json is a default; <category>.<mode>.json is a mode file.
const MODES = {
  dark: {
    kind: 'theme',
    selectors: ['[data-theme="dark"]'],
    media: '@media (prefers-color-scheme: dark)',
    mediaSelector: ':root:not([data-theme="light"])',
  },
  compact: { kind: 'density', selectors: ['[data-density="compact"]'] },
  reduced: {
    kind: 'motion',
    selectors: ['[data-motion="reduced"]'],
    media: '@media (prefers-reduced-motion: reduce)',
    mediaSelector: ':root',
  },
};

const files = readdirSync(SRC).filter((f) => f.endsWith('.json')).sort();
const defaults = files.filter((f) => f.split('.').length === 2).map((f) => path.join(SRC, f));
const modeFiles = files
  .filter((f) => f.split('.').length === 3)
  .map((f) => ({ file: path.join(SRC, f), mode: f.split('.')[1] }));

// ---- Mode validation -------------------------------------------------------
function leafPaths(obj, prefix = []) {
  const out = [];
  for (const [k, v] of Object.entries(obj)) {
    if (k.startsWith('$')) continue;
    if (v && typeof v === 'object' && '$value' in v) out.push([...prefix, k].join('.'));
    else if (v && typeof v === 'object') out.push(...leafPaths(v, [...prefix, k]));
  }
  return out;
}
const defaultPaths = new Set(defaults.flatMap((f) => leafPaths(JSON.parse(readFileSync(f, 'utf8')))));
const changedBy = new Map(); // token path -> mode kind
const errors = [];
for (const { file, mode } of modeFiles) {
  const def = MODES[mode];
  if (!def) {
    errors.push(`${file}: unknown mode "${mode}" (expected ${Object.keys(MODES).join(', ')})`);
    continue;
  }
  for (const p of leafPaths(JSON.parse(readFileSync(file, 'utf8')))) {
    if (!defaultPaths.has(p)) errors.push(`${file}: "${p}" is not defined in the defaults`);
    const prev = changedBy.get(p);
    if (prev && prev !== def.kind) errors.push(`${file}: "${p}" is changed by both ${prev} and ${def.kind} modes`);
    changedBy.set(p, def.kind);
  }
}
if (errors.length) {
  console.error('Token compile failed:\n  ' + errors.join('\n  '));
  process.exit(1);
}

// ---- Style Dictionary ------------------------------------------------------
const cssVars = (tokens) => tokens.map((t) => `  --${t.name}: ${t.$value ?? t.value};`).join('\n');

async function compile(source, filter) {
  const sd = new StyleDictionary({
    source,
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: { css: { transformGroup: 'css' } },
  });
  const platform = await sd.exportPlatform('css');
  const all = [];
  const walk = (o) => {
    for (const v of Object.values(o)) {
      if (v && typeof v === 'object' && 'name' in v && ('$value' in v || 'value' in v)) all.push(v);
      else if (v && typeof v === 'object') walk(v);
    }
  };
  walk(platform);
  return filter ? all.filter(filter) : all;
}

const base = await compile(defaults);
let css = `${HEADER}\n\n:root {\n${cssVars(base)}\n}\n`;

const modeTokens = {};
for (const def of Object.keys(MODES)) {
  const its = modeFiles.filter((m) => m.mode === def);
  if (!its.length) continue;
  // Defaults plus this mode's files; keep only tokens that come from the mode files.
  const fromMode = new Set(its.map((m) => path.resolve(m.file)));
  const tokens = await compile([...defaults, ...its.map((m) => m.file)], (t) =>
    fromMode.has(path.resolve(t.filePath)),
  );
  modeTokens[def] = tokens;
  const m = MODES[def];
  css += `\n${m.selectors.join(', ')} {\n${cssVars(tokens)}\n}\n`;
  if (m.media) css += `\n${m.media} {\n  ${m.mediaSelector} {\n${cssVars(tokens).replace(/^/gm, '  ')}\n  }\n}\n`;
}

mkdirSync(OUT, { recursive: true });
writeFileSync(path.join(OUT, 'tokens.css'), css);

// ---- Tailwind 4 theme mapping (role tokens only, no primitive ramps) -------
const byPath = (prefix) => base.filter((t) => t.path[0] === prefix);
const lines = [];
for (const t of byPath('color')) lines.push(`  --color-${t.path.slice(1).join('-')}: var(--${t.name});`);
for (const t of byPath('font')) lines.push(`  --font-${t.path[1]}: var(--${t.name});`);
const roles = [...new Set(byPath('type').map((t) => t.path[1]))];
for (const r of roles) {
  lines.push(`  --text-${r}: var(--type-${r}-size);`);
  lines.push(`  --text-${r}--line-height: var(--type-${r}-line-height);`);
  lines.push(`  --text-${r}--font-weight: var(--type-${r}-weight);`);
  lines.push(`  --text-${r}--letter-spacing: var(--type-${r}-letter-spacing);`);
}
for (const t of byPath('radius')) lines.push(`  --radius-${t.path[1]}: var(--${t.name});`);
for (const t of byPath('space')) lines.push(`  --spacing-${t.path[1]}: var(--${t.name});`);
for (const t of byPath('layout')) lines.push(`  --spacing-${t.path[1]}: var(--${t.name});`);
for (const t of byPath('shadow')) lines.push(`  --shadow-${t.path[1]}: var(--${t.name});`);
const theme = `${HEADER}\n\n/* Remove Tailwind's default palette: only the system's color roles exist. */\n@theme {\n  --color-*: initial;\n}\n\n@theme inline reference {\n${lines.join('\n')}\n}\n`;
writeFileSync(path.join(OUT, 'tailwind-theme.css'), theme);

// Self-reference check: a custom property must never point at itself.
for (const [file, text] of [['tokens.css', css], ['tailwind-theme.css', theme]]) {
  for (const m of text.matchAll(/--([\w-]+):\s*var\(--([\w-]+)\)/g)) {
    if (m[1] === m[2] && file === 'tokens.css') {
      console.error(`Token compile failed: --${m[1]} refers to itself in ${file}`);
      process.exit(1);
    }
  }
}

// ---- DESIGN.md front matter -------------------------------------------------
const sistema = JSON.parse(readFileSync('sistema.json', 'utf8'));
const q = (v) => `"${String(v).replace(/"/g, '\\"')}"`;
const get = (p) => base.find((t) => t.path.join('.') === p);
const raw = (t) => t.original.$value;
const fm = [
  '# Generated by style-dictionary.config.mjs from tokens/src/. Do not edit by hand.',
  '# Colors are the light (primary) theme; dark values are in tokens/src/color.dark.json.',
  'version: alpha',
  `name: ${sistema.project.name}`,
  'colors:',
  ...byPath('color')
    .filter((t) => /^#[0-9a-f]{6}$/i.test(t.$value))
    .map((t) => `  ${t.path.slice(1).join('-')}: ${q(t.$value.toUpperCase())}`),
  'typography:',
  ...roles.flatMap((r) => {
    const fam = get(`type.${r}.family`);
    const famName = Array.isArray(raw(fam)) ? raw(fam)[0] : String(fam.$value).split(',')[0].replace(/["']/g, '').trim();
    return [
      `  ${r}:`,
      `    fontFamily: ${famName}`,
      `    fontSize: ${get(`type.${r}.size`).$value}`,
      `    fontWeight: ${get(`type.${r}.weight`).$value}`,
      `    lineHeight: ${get(`type.${r}.line-height`).$value}`,
      `    letterSpacing: ${get(`type.${r}.letter-spacing`).$value}`,
    ];
  }),
  'rounded:',
  ...byPath('radius').map((t) => `  ${t.path[1]}: ${t.$value}`),
  'spacing:',
  ...byPath('space').map((t) => `  ${q(t.path[1])}: ${t.$value}`),
  ...byPath('layout').map((t) => `  ${t.path[1]}: ${t.$value}`),
];
const design = readFileSync('DESIGN.md', 'utf8');
const body = design.startsWith('---\n') ? design.slice(design.indexOf('\n---\n', 4) + 5) : design;
writeFileSync('DESIGN.md', `---\n${fm.join('\n')}\n---\n${body}`);

console.log(`Compiled ${base.length} default tokens from ${defaults.length} files`);
for (const [m, t] of Object.entries(modeTokens)) console.log(`  mode ${m}: ${t.length} tokens`);
console.log(`Wrote ${OUT}/tokens.css, ${OUT}/tailwind-theme.css, DESIGN.md front matter`);
